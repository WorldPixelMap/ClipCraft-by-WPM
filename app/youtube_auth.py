"""1-Click YouTube Sign-In Helper: opens an isolated browser window for the user and exports cookies.txt."""

from __future__ import annotations

import asyncio
import json
import os
import shutil
import socket
import subprocess
import threading
import time
import urllib.request
from pathlib import Path

import websockets

from app.youtube_service import COOKIES_FILE, has_cookies_file

BASE_DIR = Path(__file__).resolve().parent.parent
AUTH_PROFILE_DIR = BASE_DIR / ".yt_auth_profile"

YOUTUBE_LOGIN_URL = (
    "https://accounts.google.com/ServiceLogin"
    "?service=youtube&passive=true&continue=https%3A%2F%2Fwww.youtube.com%2F"
)
ALLOWED_COOKIE_DOMAINS = (
    "youtube.com",
    "google.com",
    "googlevideo.com",
    "ytimg.com",
    "googleusercontent.com",
    "youtu.be",
)


def find_chromium_browser() -> str | None:
    """Locate Microsoft Edge, Google Chrome, or Brave executable on Windows/macOS/Linux."""
    candidates = [
        Path(r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe"),
        Path(r"C:\Program Files\Microsoft\Edge\Application\msedge.exe"),
        Path(r"C:\Program Files\Google\Chrome\Application\chrome.exe"),
        Path(r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe"),
        Path(r"C:\Program Files\BraveSoftware\Brave-Browser\Application\brave.exe"),
    ]
    local_app = os.environ.get("LOCALAPPDATA")
    if local_app:
        candidates.append(Path(local_app) / r"Google\Chrome\Application\chrome.exe")
        candidates.append(Path(local_app) / r"Microsoft\Edge\Application\msedge.exe")

    for p in candidates:
        if p.exists():
            return str(p)
    for name in ("msedge", "chrome", "google-chrome", "chromium", "brave"):
        found = shutil.which(name)
        if found:
            return found
    return None


def _pick_free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(("127.0.0.1", 0))
        return int(s.getsockname()[1])


def cookies_to_netscape_text(cdp_cookies: list[dict]) -> tuple[str, bool]:
    """
    Convert CDP Storage.getCookies objects to Netscape cookies.txt string.
    Returns (netscape_text, has_youtube_auth_cookie).
    """
    lines = ["# Netscape HTTP Cookie File", "# Generated by Local ClipCraft by WPM"]
    has_auth = False
    has_yt = False

    for c in cdp_cookies:
        domain = str(c.get("domain") or "").strip()
        if not domain:
            continue
        bare = domain.lstrip(".").lower()
        if not any(bare == d or bare.endswith("." + d) for d in ALLOWED_COOKIE_DOMAINS):
            continue

        name = str(c.get("name") or "").replace("\t", " ").replace("\n", "").replace("\r", "")
        value = str(c.get("value") or "").replace("\t", " ").replace("\n", "").replace("\r", "")
        if not name:
            continue

        if bare.endswith("youtube.com"):
            has_yt = True
            if name in {"LOGIN_INFO", "SAPISID", "__Secure-3PAPISID", "__Secure-1PAPISID", "SID"}:
                has_auth = True
        elif bare.endswith("google.com") and name in {"SAPISID", "__Secure-3PAPISID", "SID"}:
            has_auth = True

        flag = "TRUE" if domain.startswith(".") else "FALSE"
        path = str(c.get("path") or "/")
        secure = "TRUE" if c.get("secure") else "FALSE"
        raw_exp = float(c.get("expires") or 0)
        expires = str(max(0, int(raw_exp))) if raw_exp > 0 else "0"
        lines.append(f"{domain}\t{flag}\t{path}\t{secure}\t{expires}\t{name}\t{value}")

    return "\n".join(lines) + "\n", (has_auth and has_yt)


async def _fetch_cdp_cookies(ws_url: str) -> list[dict]:
    async with websockets.connect(ws_url, open_timeout=3, close_timeout=2) as ws:
        await ws.send(json.dumps({"id": 1, "method": "Storage.getCookies"}))
        raw = await asyncio.wait_for(ws.recv(), timeout=3)
        data = json.loads(raw)
        return data.get("result", {}).get("cookies", [])


def _query_cdp(port: int) -> tuple[str | None, list[str]]:
    """Return (browser_ws_url, open_tab_urls) from local CDP HTTP endpoint."""
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/json/version", timeout=1) as r:
            ver = json.loads(r.read().decode())
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/json/list", timeout=1) as r:
            tabs = json.loads(r.read().decode())
        urls = [str(t.get("url") or "") for t in tabs if isinstance(t, dict)]
        return ver.get("webSocketDebuggerUrl"), urls
    except Exception:
        return None, []


class YouTubeAuthManager:
    """Manages an isolated popup browser window so the user can sign into YouTube in 1 click."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._proc: subprocess.Popen | None = None
        self._port: int | None = None
        self._status: str = "signed_in" if has_cookies_file() else "idle"
        self._message: str = "YouTube cookies loaded." if has_cookies_file() else ""

    def get_status(self) -> dict:
        with self._lock:
            return {
                "status": self._status,
                "message": self._message,
                "cookies_file_loaded": has_cookies_file(),
                "browser_login_available": find_chromium_browser() is not None,
            }

    def start_login(self) -> dict:
        exe = find_chromium_browser()
        if not exe:
            raise RuntimeError("Microsoft Edge or Google Chrome was not found on this machine.")

        self.cancel_login(quiet=True)
        AUTH_PROFILE_DIR.mkdir(parents=True, exist_ok=True)
        port = _pick_free_port()

        cmd = [
            exe,
            f"--user-data-dir={AUTH_PROFILE_DIR}",
            f"--remote-debugging-port={port}",
            "--no-first-run",
            "--no-default-browser-check",
            "--window-size=560,760",
            f"--app={YOUTUBE_LOGIN_URL}",
        ]
        proc = subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

        with self._lock:
            self._proc = proc
            self._port = port
            self._status = "waiting_for_login"
            self._message = "Sign into YouTube in the popup window — cookies will save automatically!"

        t = threading.Thread(target=self._watch_login, args=(proc, port), daemon=True)
        t.start()
        return self.get_status()

    def _close_proc(self, proc: subprocess.Popen | None) -> None:
        if not proc:
            return
        try:
            if proc.poll() is None:
                proc.terminate()
                proc.wait(timeout=3)
        except Exception:
            try:
                proc.kill()
            except Exception:
                pass

    def _try_save_from_port(self, port: int, require_youtube_tab: bool) -> bool:
        ws_url, tab_urls = _query_cdp(port)
        if not ws_url:
            return False
        if require_youtube_tab and not any(
            u.startswith(("https://www.youtube.com/", "https://m.youtube.com/")) for u in tab_urls
        ):
            return False

        cookies = asyncio.run(_fetch_cdp_cookies(ws_url))
        text, has_auth = cookies_to_netscape_text(cookies)
        if not has_auth:
            return False

        COOKIES_FILE.write_text(text, encoding="utf-8")
        return True

    def _watch_login(self, proc: subprocess.Popen, port: int) -> None:
        deadline = time.time() + 300  # 5 minute timeout
        while time.time() < deadline:
            with self._lock:
                if self._proc is not proc or self._status != "waiting_for_login":
                    return

            if proc.poll() is not None:
                with self._lock:
                    if self._proc is proc and self._status == "waiting_for_login":
                        self._proc = None
                        self._port = None
                        self._status = "signed_in" if has_cookies_file() else "cancelled"
                        self._message = (
                            "YouTube sign-in saved!"
                            if has_cookies_file()
                            else "Sign-in window closed before YouTube login finished."
                        )
                return

            try:
                if self._try_save_from_port(port, require_youtube_tab=True):
                    # Brief pause so YouTube finishes setting final cookies after redirect
                    time.sleep(0.8)
                    self._try_save_from_port(port, require_youtube_tab=True)
                    with self._lock:
                        self._status = "signed_in"
                        self._message = "Signed into YouTube! Ready to generate clips."
                        self._proc = None
                        self._port = None
                    self._close_proc(proc)
                    return
            except Exception:
                pass

            time.sleep(1.0)

        with self._lock:
            if self._proc is proc:
                self._status = "cancelled"
                self._message = "Sign-in timed out."
                self._proc = None
                self._port = None
        self._close_proc(proc)

    def save_now(self) -> dict:
        """Manually capture cookies from the active login popup window."""
        with self._lock:
            proc = self._proc
            port = self._port
        if not proc or not port or proc.poll() is not None:
            raise RuntimeError("No active YouTube sign-in window is open.")

        if not self._try_save_from_port(port, require_youtube_tab=False):
            raise RuntimeError("Not signed into YouTube yet — finish signing in first inside the popup window.")

        with self._lock:
            self._status = "signed_in"
            self._message = "Signed into YouTube! Ready to generate clips."
            self._proc = None
            self._port = None
        self._close_proc(proc)
        return self.get_status()

    def cancel_login(self, quiet: bool = False) -> dict:
        with self._lock:
            proc = self._proc
            self._proc = None
            self._port = None
            if not quiet:
                self._status = "signed_in" if has_cookies_file() else "idle"
                self._message = "" if not has_cookies_file() else "YouTube cookies loaded."
        self._close_proc(proc)
        return self.get_status()

    def clear_session(self) -> dict:
        self.cancel_login(quiet=True)
        if COOKIES_FILE.exists():
            COOKIES_FILE.unlink(missing_ok=True)
        if AUTH_PROFILE_DIR.exists():
            shutil.rmtree(AUTH_PROFILE_DIR, ignore_errors=True)
        with self._lock:
            self._status = "idle"
            self._message = "Signed out of YouTube."
        return self.get_status()


youtube_auth_manager = YouTubeAuthManager()
